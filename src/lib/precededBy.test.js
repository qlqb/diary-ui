import { describe, it, expect } from 'vitest';
import { precededByLabel, shortTitle } from './precededBy.js';

const B = (title, startAt, endAt) => ({ title, startAt, endAt });

describe('precededByLabel — 앞 일정 기준 표현', () => {
  it('같은 날 바로 앞에서 끝난 일정에 잇는다', () => {
    expect(precededByLabel('2026-11-20T10:45:00', [B('자료구조', '2026-11-20T09:00:00', '2026-11-20T10:15:00')]))
      .toBe('자료구조 끝나고 30분 뒤');
  });

  it('5분 안이면 "바로"라고 말한다', () => {
    expect(precededByLabel('2026-11-19T15:30', [B('치과 정기검진', '2026-11-19T14:30', '2026-11-19T15:30')]))
      .toBe('치과 정기검진 끝나고 바로');
  });

  it('여럿이면 가장 늦게 끝난 것에 잇는다', () => {
    expect(precededByLabel('2026-11-19T16:00', [
      B('스마트앱', '2026-11-19T10:00', '2026-11-19T12:50'),
      B('치과', '2026-11-19T14:30', '2026-11-19T15:30'),
      B('빅데이터분석', '2026-11-19T13:00', '2026-11-19T15:45'),
    ])).toBe('빅데이터분석 끝나고 15분 뒤');
  });

  it('간격이 한 시간보다 길면 잇지 않는다(시각이 낫다)', () => {
    expect(precededByLabel('2026-11-19T19:00', [B('수업', '2026-11-19T13:00', '2026-11-19T15:45')])).toBeNull();
  });

  it('겹치거나 뒤에 있는 일정, 다른 날 일정에는 잇지 않는다', () => {
    expect(precededByLabel('2026-11-19T19:30', [B('소켓 서버 과제', '2026-11-19T19:00', '2026-11-19T20:30')])).toBeNull();
    expect(precededByLabel('2026-11-21T09:00', [B('편의점 알바', '2026-11-20T22:00', '2026-11-21T02:00')])).toBeNull();
    expect(precededByLabel('2026-11-22T09:30', [B('어제 일', '2026-11-21T09:00', '2026-11-21T09:20')])).toBeNull();
  });

  it('전날 밤에 시작해 자정을 넘긴 일정은 그날의 앞 일정이 아니다', () => {
    expect(precededByLabel('2026-11-21T00:40:00', [B('편의점 알바', '2026-11-20T22:00:00', '2026-11-21T00:30:00')])).toBeNull();
  });

  it('초까지 비교한다(같은 분 안에서 앞뒤가 바뀌지 않는다)', () => {
    expect(precededByLabel('2026-11-19T10:00:10', [B('수업', '2026-11-19T09:00:00', '2026-11-19T10:00:50')])).toBeNull();
    expect(precededByLabel('2026-11-19T11:00:30', [B('수업', '2026-11-19T09:00:00', '2026-11-19T10:00:00')])).toBeNull(); // 60분 30초
  });

  it('앞에 아무것도 없으면 null(화면은 시각만 쓴다)', () => {
    expect(precededByLabel('2026-11-22T15:00', [])).toBeNull();
    expect(precededByLabel(null, [B('x', '2026-11-22T14:00', '2026-11-22T14:30')])).toBeNull();
  });

  it('긴 과목명은 문장에 넣을 만큼 줄인다', () => {
    expect(shortTitle('스마트앱프로젝트 — 센서활용 프로그래밍 실습 (2분반)')).toBe('스마트앱프로젝트');
    expect(shortTitle('빅데이터분석 및 머신러닝 기초 이론과 데이터 시각화')).toBe('빅데이터분석 및 머신러닝 …');
    expect(precededByLabel('2026-11-19T13:20', [B('스마트앱프로젝트 — 센서활용 프로그래밍 실습 (2분반)', '2026-11-19T10:00', '2026-11-19T12:50')]))
      .toBe('스마트앱프로젝트 끝나고 30분 뒤');
  });
});
